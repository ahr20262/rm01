// 对应截图：images/4-P5712-apples.png（Project P5712）
// 输入苹果个数 a，输出 "Today, I ate a apples"
#include <iostream>

using namespace std;

int main() {
    int a;
    cin >> a;
    if (a > 1)
    {
        cout << "Today, I ate " << a << " apples" << endl;
    }
    else
    {
        cout << "Today, I ate " << a << " apples" << endl;
    }
    return 0;
}
